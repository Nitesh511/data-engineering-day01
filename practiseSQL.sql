SELECT
	SUBJECT,
	COUNT(*) AS TOTAL_STUDENTS,
	AVG(GRADE) AS AVERAGE_GRADE,
	MAX(GRADE) AS HIGHEST_GRADE,
	MIN(GRADE) AS LOWEST_GRADE
FROM
	STUDENTS
GROUP BY
	SUBJECT
SELECT
	SUBJECT,
	AVG(GRADE) AS AVERAGE_GRADE
FROM
	STUDENTS
GROUP BY
	SUBJECT
HAVING
	AVG(GRADE) > 75;

SELECT
	NAME,
	SUBJECT,
	GRADE,
	RANK() OVER (
		PARTITION BY
			SUBJECT
		ORDER BY
			GRADE DESC
	) AS RANK_IN_SUBJECT
FROM
	STUDENTS;

